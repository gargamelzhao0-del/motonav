"""Generate bounded LVGL 4-bit fonts from the pinned OFL sources in fonts/README.md.

Requires Pillow and fontTools. Source TTFs are supplied locally; no network access during builds.
Generated sources are checked in so production needs neither Python nor font tools.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source_directory', type=Path)
parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1]/'components/motonav_ui/fonts')
args = parser.parse_args()
pins = {
    'Anton-Regular.ttf': 'a4ba3a92350ebb031da0cb47630ac49eb265082ca1bc0450442f4a83ab947cab',
    'BarlowCondensed-Bold.ttf': 'e476562ec9c1e16cf16475895b511f08c804f438cc9a9f80a44ea50a0eeb5b65',
    'NotoSansSC[wght].ttf': 'a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da',
}
for name, digest in pins.items():
    assert hashlib.sha256((args.source_directory/name).read_bytes()).hexdigest() == digest, name

def generate(name, filename, size, charset, weight=None, fallback=None):
    font = ImageFont.truetype(str(args.source_directory/filename), size)
    if weight is not None:
        font.set_variation_by_axes([weight])
    characters = sorted(set(charset))
    bitmap, descriptors = [], ['    {0,0,0,0,0,0},']
    top, bottom = 0, 0
    for char in characters:
        left, y0, right, y1 = font.getbbox(char, anchor='ls')
        width, height = right-left, y1-y0
        top, bottom = min(top, y0), max(bottom, y1)
        image = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -y0), char, font=font, fill=255, anchor='ls')
        pixels = [(v*15+127)//255 for v in image.getdata()] if width and height else []
        offset = len(bitmap)
        if len(pixels)%2:
            pixels.append(0)
        bitmap.extend((pixels[i]<<4)|pixels[i+1] for i in range(0, len(pixels), 2))
        descriptors.append(f'    {{{offset},{round(font.getlength(char)*16)},{width},{height},{left},{-y1}}},')
    start, end = ord(characters[0]), ord(characters[-1])
    assert len(bitmap)<1048576, 'LVGL compact glyph offset limit'
    source = ['// Generated by tools/generate_ui_fonts.py; see accompanying OFL licenses.', '#include "lvgl.h"',
              f'extern const lv_font_t {fallback};' if fallback else '',
              'static const uint8_t bitmap[] = {']
    source.extend('    '+','.join(f'0x{x:02x}' for x in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24))
    source.extend(['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', *descriptors, '};',
                   'static const uint16_t unicodes[] = {'])
    offsets = [ord(c)-start for c in characters]
    source.extend('    '+','.join(map(str, offsets[i:i+24]))+',' for i in range(0,len(offsets),24))
    line_height,baseline=(25,6) if filename.startswith('Noto') else (bottom-top+2,bottom+1)
    source.extend(['};', 'static const lv_font_fmt_txt_cmap_t cmaps[] = {{',
        f'    .range_start={start}, .range_length={end-start+1}, .glyph_id_start=1,',
        f'    .unicode_list=unicodes, .list_length={len(characters)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY',
        '}};', 'static const lv_font_fmt_txt_dsc_t descriptor = {',
        '    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps, .cmap_num=1, .bpp=4, .bitmap_format=0',
        '};', f'const lv_font_t {name} = {{',
        '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
        f'    .line_height={line_height}, .base_line={baseline}, .subpx=LV_FONT_SUBPX_NONE, .dsc=&descriptor,',
        f'    .fallback=&{fallback}' if fallback else '    .fallback=NULL',
        '};', ''])
    (args.output/(name+'.c')).write_text('\n'.join(source),encoding='utf-8')
    print(name, len(characters), 'glyphs,', len(bitmap), 'bitmap bytes, height', line_height, 'baseline', baseline)

args.output.mkdir(parents=True, exist_ok=True)
ascii_chars=''.join(chr(n) for n in range(32,127))
cjk=set(ascii_chars+'©°□·')
for high in range(0xa1,0xf8):
    for low in range(0xa1,0xff):
        try:
            cjk.add(bytes([high,low]).decode('gb2312'))
        except UnicodeDecodeError:
            pass
generate('motonav_speed_66','Anton-Regular.ttf',66,' -0123456789')
generate('motonav_distance_36','BarlowCondensed-Bold.ttf',36,ascii_chars)
generate('motonav_small_14','BarlowCondensed-Bold.ttf',14,ascii_chars+'©')
with TTFont(args.source_directory/'NotoSansSC[wght].ttf') as source_font:
    supported=source_font.getBestCmap()
    # Common Traditional Chinese and accented names are present in real OSM.
    # Keep existing GB2312 fonts first, then bounded fallback chunks in flash.
    extra=sorted({chr(n) for n in [*range(0x4e00,0xa000),*range(0xa0,0x250)]
                  if n in supported}-cjk)
chunks=[extra[i:i+5000] for i in range(0,len(extra),5000)]
for i,characters in enumerate(chunks):
    fallback=f'motonav_ui_18_extra_{i+1}' if i+1<len(chunks) else None
    generate(f'motonav_ui_18_extra_{i}','NotoSansSC[wght].ttf',18,characters,500,fallback)
generate('motonav_ui_18_ext','NotoSansSC[wght].ttf',18,[c for c in cjk if ord(c)>0x7000],500,'motonav_ui_18_extra_0')
generate('motonav_ui_18','NotoSansSC[wght].ttf',18,[c for c in cjk if ord(c)<=0x7000],500,'motonav_ui_18_ext')
