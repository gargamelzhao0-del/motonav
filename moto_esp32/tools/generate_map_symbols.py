"""Build antialiased, font-independent POI symbols from simple vector primitives.

Pillow is only required for regeneration. Production uses checked-in ARGB8888.
"""
from pathlib import Path
from PIL import Image, ImageDraw

root=Path(__file__).resolve().parents[1]/'components/motonav_ui'
out=['// Generated by tools/generate_map_symbols.py; original MotoNav vector symbols.',
     '#pragma once', '#include "lvgl.h"', 'namespace motonav {']
for kind in range(2,9):
    for size in (12,15,18):
        scale=8
        image=Image.new('RGBA',(18*scale,18*scale))
        d=ImageDraw.Draw(image)
        def box(bounds,fill):d.rectangle(tuple(round(v*scale) for v in bounds),fill=fill)
        def line(points,width=1.4):d.line([(round(x*scale),round(y*scale)) for x,y in points],fill='#f2f3ee',width=round(width*scale),joint='curve')
        def polygon(points):d.polygon([(round(x*scale),round(y*scale)) for x,y in points],fill='#f2f3ee')
        d.ellipse((scale,scale,17*scale,17*scale),fill='#f2f3ee')
        d.ellipse((2.2*scale,2.2*scale,15.8*scale,15.8*scale),fill='#1b1e1f')
        if kind==2: # Landmark: roof and columns.
            polygon([(4.5,7),(9,4),(13.5,7)])
            line([(4.5,13),(13.5,13)])
            for x in (6,9,12):line([(x,8),(x,12)],1.1)
        elif kind==3:
            box((5,4.5,9.5,13.5),'#f2f3ee');box((6,5.5,8.5,7.5),'#1b1e1f')
            line([(9.5,8),(12,8.5),(12,12.5),(13,12.5),(13,6.5),(11.5,5.5)],1.1)
        elif kind==4:line([(6.5,13.5),(6.5,4.5),(11,4.5),(12,5.5),(12,8),(11,9),(6.5,9)],1.7)
        elif kind==5:
            line([(6,4.5),(6,13.5)],1.2);line([(4.4,4.5),(4.4,8),(7.6,8),(7.6,4.5)],1.1)
            line([(11.5,4.5),(10,8.5),(11.5,8.5),(11.5,13.5)],1.4)
        elif kind==6:
            box((7.5,4.5,10.5,13.5),'#f2f3ee');box((4.5,7.5,13.5,10.5),'#f2f3ee')
        elif kind==7:
            box((5.5,4.5,12.5,11.5),'#f2f3ee');box((6.5,5.5,11.5,8),'#1b1e1f')
            line([(7,11),(5.5,13.5)],1.1);line([(11,11),(12.5,13.5)],1.1)
        else:
            polygon([(9,4),(5.5,9),(7,9),(4.5,12),(13.5,12),(11,9),(12.5,9)])
            line([(9,11),(9,14)],1.2)
        image=image.resize((size,size),Image.Resampling.LANCZOS)
        values=[(a<<24)|(r<<16)|(g<<8)|b for r,g,b,a in image.getdata()]
        name=f'poi_{kind}_{size}'
        out.append(f'static const uint32_t {name}_pixels[]={{')
        out.extend('    '+','.join(f'0x{v:08x}' for v in values[i:i+8])+',' for i in range(0,len(values),8))
        out.extend(['};',f'static const lv_image_dsc_t {name}=[]{{lv_image_dsc_t d{{}};d.header.magic=LV_IMAGE_HEADER_MAGIC;',
                    f'    d.header.cf=LV_COLOR_FORMAT_ARGB8888;d.header.w={size};d.header.h={size};d.header.stride={size*4};',
                    f'    d.data_size=sizeof({name}_pixels);d.data=reinterpret_cast<const uint8_t *>({name}_pixels);return d;}}();'])
out.append('inline const lv_image_dsc_t *map_symbol(unsigned kind,int size){switch(kind){')
for kind in range(2,9):out.append(f'case {kind}:return size==12?&poi_{kind}_12:size==15?&poi_{kind}_15:&poi_{kind}_18;')
out.extend(['default:return &poi_2_18;}}','}'])
(root/'map_symbols.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Generated seven geometric symbols at 12, 15 and 18 pixels.')
